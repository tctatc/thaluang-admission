export function Guide({ title, topics }: { title: string; topics: GuideTopic[] }) {
  return (
    <section aria-labelledby="guide-title" className="space-y-2">
      <h2 id="guide-title" className="text-xl text-brand-deep">{title}</h2>
      {topics.map((topic, index) => (
        <details key={topic.title} open={index === 0} className="group rounded-card bg-surface shadow-card ring-1 ring-line">
          <summary className="flex min-h-14 cursor-pointer list-none items-center gap-3 px-4 py-3 font-medium [&::-webkit-details-marker]:hidden">
            <span aria-hidden="true" className="grid size-8 shrink-0 place-items-center rounded-full bg-brand-soft text-sm font-semibold text-brand" data-numeric>{index + 1}</span>
            <span className="flex-1">{topic.title}</span>
            <ChevronDown className="size-5 shrink-0 text-ink-muted transition-transform group-open:rotate-180" aria-hidden="true" />
          </summary>
          <ol className="list-decimal space-y-1.5 border-t border-line py-3 pl-12 pr-4 marker:text-ink-muted">
            {topic.steps.map((step) => <li key={step}>{step}</li>)}
          </ol>
        </details>
      ))}
    </section>
  );
}
